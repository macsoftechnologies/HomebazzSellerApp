export interface OrderItem {
  id: string;
  name: string;
  price: number;
  quantity: number;
  total: number;
  image?: any;
}

export interface Order {
  id: string;
  customerName: string;
  customerPhone: string;
  customerAddress: string;
  placedAt: string;
  itemCount: number;
  totalAmount: number;
  status: 'New' | 'Processing' | 'Packed' | 'Shipped' | 'Delivered' | 'Cancelled';
  items: OrderItem[];
  paymentMode: string;
  specialInstructions?: string;
  deliveryPartner?: {
    name: string;
    phone: string;
    vehicleNumber: string;
    rating: number;
    etaMinutes: number;
  };
}

export interface Product {
  id: string;
  name: string;
  price: number;
  stock: number;
  category: string;
  status: 'In Stock' | 'Low Stock' | 'Out of Stock';
  isActive: boolean;
  ordersCount: number;
  rating: number;
  image: any;
  description: string;
  ingredients: string[];
  allergens: string[];
  shelfLife: string;
  fssaiNumber: string;
  isHandmade: boolean;
  preparationLeadTime: string;
}

export interface PayoutRecord {
  id: string;
  date: string;
  period: string;
  amount: number;
  status: 'Transferred' | 'Processing' | 'Scheduled';
  utrNumber: string;
  bankAccount: string;
  ordersCovered: number;
}

export interface NotificationItem {
  id: string;
  title: string;
  message: string;
  time: string;
  type: 'order' | 'shipping' | 'stock' | 'payout' | 'verification' | 'review';
  read: boolean;
}

